export type WeaponCategory = 'rifle' | 'smg' | 'shotgun' | 'sniper' | 'pistol' | 'melee';
export type FireMode = 'auto' | 'semi';
export type WeaponSlot = 1 | 2 | 3; // 1 = Primary, 2 = Secondary (Pistol), 3 = Melee

export interface WeaponDefinition {
  id: string;
  name: string;
  category: WeaponCategory;
  slot: WeaponSlot;
  price: number;
  killReward: number;
  fireMode: FireMode;
  rpm: number; // Rounds per minute
  magazineSize: number;
  reserveAmmoMax: number;
  reloadDuration: number; // Seconds
  drawDuration: number; // Seconds
  baseDamage: number;
  armorPenetration: number; // 0.0 to 1.0
  pellets: number; // 1 for standard firearms, 7-8 for shotguns
  effectiveRange: number; // Meters before heavy falloff
  maxRange: number;
  damageFalloffPer10m: number; // Multiplier retained per 10m (e.g., 0.96)
  headMultiplier: number;
  torsoMultiplier: number;
  limbMultiplier: number;
  baseSpreadDeg: number; // Stationary hipfire spread in degrees
  adsSpreadDeg: number; // Stationary aimed spread in degrees
  moveSpreadPenaltyDeg: number; // Added spread at full walk/run speed
  sprintSpreadPenaltyDeg: number;
  airSpreadPenaltyDeg: number;
  crouchSpreadMultiplier: number;
  spreadPerShotDeg: number;
  spreadRecoveryRate: number; // Degrees per second
  recoilPitchPerShotDeg: number;
  recoilYawVarianceDeg: number;
  recoilPattern: ReadonlyArray<{ pitch: number; yaw: number }>;
  recoilRecoveryRate: number; // Degrees per second
  adsFovMultiplier: number; // e.g., 0.85 for iron sights, 0.35 for sniper scope
  movementSpeedMultiplier: number; // 0.82 (heavy sniper) to 1.08 (knife)
  audioPitchHz: number;
  audioDurationSec: number;
  viewmodelColor: number;
  viewmodelAccentColor: number;
  barrelLength: number;
}

